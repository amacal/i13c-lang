from dataclasses import dataclass
from typing import Protocol

from i13c.syntax.tree import function, literals, snippet, types
from i13c.syntax.tree.core import Path

Flags = snippet.Flags | function.Flags
Signature = function.Signature | snippet.Signature

class Visitor(Protocol):
    def on_program(self, program: Program, path: Path): ...

    # shared
    def on_flags(self, flags: Flags, path: Path): ...
    def on_signature(self, signature: Signature, path: Path): ...

    # snippet related
    def on_snippet(self, snippet: snippet.Snippet, path: Path): ...
    def on_slot(self, slot: snippet.Slot, path: Path): ...
    def on_bind(self, bind: snippet.Bind, path: Path): ...
    def on_result(self, result: snippet.Result, path: Path): ...
    def on_label(self, label: snippet.Label, path: Path): ...
    def on_instruction(self, instruction: snippet.Instruction, path: Path): ...
    def on_mnemonic(self, mnemonic: snippet.Mnemonic, path: Path): ...
    def on_immediate(self, immediate: snippet.Immediate, path: Path): ...
    def on_register(self, register: snippet.Register, path: Path): ...
    def on_reference(self, reference: snippet.Reference, path: Path): ...
    def on_address(self, address: snippet.Address, path: Path): ...
    def on_index(self, index: snippet.Index, path: Path): ...
    def on_displacement(self, displacement: snippet.Displacement, path: Path): ...

    # function related
    def on_function(self, function: function.Function, path: Path): ...
    def on_statement(self, statement: function.Statement, path: Path): ...
    def on_call(self, call: function.CallStatement, path: Path): ...
    def on_callsite(self, callsite: function.CallSite, path: Path): ...
    def on_assign(self, assign: function.AssignStatement, path: Path): ...
    def on_value(self, value: function.Value, path: Path): ...
    def on_literal(self, literal: function.Literal, path: Path): ...
    def on_expression(self, expression: function.Expression, path: Path): ...
    def on_operand(self, operand: snippet.Operand, path: Path): ...
    def on_parameter(self, parameter: function.Parameter, path: Path): ...

    # types related
    def on_type(self, type: types.Type, path: Path): ...
    def on_range(self, range: types.Range, path: Path): ...


@dataclass(kw_only=True, eq=False)
class Program:
    functions: list[function.Function]
    snippets: list[snippet.Snippet]

    def accept(self, visitor: Visitor, path: Path):
        visitor.on_program(self, path)

        with path.push(self) as node:
            for entry in self.snippets:
                entry.accept(visitor, node)

            for entry in self.functions:
                entry.accept(visitor, node)
